def _safe_print(msg: str):
    try:
        print(msg)
    except Exception:
        try:
            print(msg.encode('ascii', errors='replace').decode('ascii'))
        except Exception:
            pass

def save_image(img: np.ndarray,
               output_dir: str | Path = "outputs/corrected",
               filename: str | None = None,
               format: str = "png") -> Path:
    """
    Save a processed image to disk.

    Args:
        img:        Image array to save
        output_dir: Output directory
        filename:   Optional filename (auto-generated if None)
        format:     "png" | "tiff" | "jpg"

    Returns:
        Path to saved file
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    if filename is None:
        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = f"corrected_{ts}.{format}"

    out_path = output_dir / filename
    cv2.imwrite(str(out_path), img)
    _safe_print(f"[EXPORT] Image saved -> {out_path}")
    return out_path


def save_side_by_side(original: np.ndarray,
                       corrected: np.ndarray,
                       output_path: str | Path) -> Path:
    """Create and save a before/after side-by-side comparison image."""
    if original.ndim == 2:
        original = cv2.cvtColor(original, cv2.COLOR_GRAY2BGR)
    if corrected.ndim == 2:
        corrected = cv2.cvtColor(corrected, cv2.COLOR_GRAY2BGR)

    # Resize both to same height
    h = max(original.shape[0], corrected.shape[0])
    
    def resize_h(img, target_h):
        scale = target_h / img.shape[0]
        new_w = int(img.shape[1] * scale)
        return cv2.resize(img, (new_w, target_h), interpolation=cv2.INTER_LANCZOS4)
    
    orig_r = resize_h(original,  h)
    corr_r = resize_h(corrected, h)
    
    # Add labels
    def add_label(img, text):
        out = img.copy()
        cv2.rectangle(out, (0, 0), (out.shape[1], 50), (30, 30, 30), -1)
        cv2.putText(out, text, (15, 35),
                   cv2.FONT_HERSHEY_SIMPLEX, 1.0, (255, 255, 255), 2)
        return out
    
    orig_r = add_label(orig_r,  "ORIGINAL (Warped)")
    corr_r = add_label(corr_r,  "CORRECTED (Dewarped)")
    
    # Separator
    sep = np.ones((h, 10, 3), dtype=np.uint8) * 80
    
    combined = np.hstack([orig_r, sep, corr_r])
    
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(output_path), combined)
    _safe_print(f"[EXPORT] Side-by-side saved -> {output_path}")
    return output_path


