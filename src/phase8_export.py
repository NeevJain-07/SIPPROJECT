class DocumentQualityPDF(FPDF):
    """Custom FPDF class for quality report styling."""
    
    def header(self):
        self.set_fill_color(20, 20, 40)
        self.rect(0, 0, 210, 20, "F")
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 13)
        self.set_y(5)
        self.cell(0, 10, "Document Quality Assessment Report", align="C")
        self.set_text_color(0, 0, 0)
        self.ln(15)
    
    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by SIP Document Scanner",
                  align="C")


def generate_pdf_report(report: QualityReport,
                         original_img: np.ndarray,
                         corrected_img: np.ndarray,
                         output_path: str | Path,
                         tmp_dir: str | Path = "outputs/reports/tmp") -> Path:
    """
    Generate a full PDF quality report with:
      - Before/after thumbnails
      - Quality metrics table
      - Score gauge
      - Recommendations

    Args:
        report:        QualityReport instance
        original_img:  Original (warped) image
        corrected_img: Corrected (dewarped) image
        output_path:   Output PDF path
        tmp_dir:       Temp directory for intermediate images

    Returns:
        Path to generated PDF
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_dir = Path(tmp_dir)
    tmp_dir.mkdir(parents=True, exist_ok=True)

    if original_img.ndim == 2:
        original_img = cv2.cvtColor(original_img, cv2.COLOR_GRAY2BGR)
    if corrected_img.ndim == 2:
        corrected_img = cv2.cvtColor(corrected_img, cv2.COLOR_GRAY2BGR)
    
    # Save temp thumbnail images
    def save_thumb(img, fname):
        h, w = img.shape[:2]
        max_dim = 600
        if max(h, w) > max_dim:
            scale = max_dim / max(h, w)
            img = cv2.resize(img, (int(w * scale), int(h * scale)))
        path = tmp_dir / fname
        cv2.imwrite(str(path), img)
        return str(path)
    
    orig_thumb  = save_thumb(original_img,  "orig_thumb.jpg")
    corr_thumb  = save_thumb(corrected_img, "corr_thumb.jpg")
    
    pdf = DocumentQualityPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    
    # ── Title & Timestamp ─────────────────────────────────────────────────────
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(20, 20, 60)
    pdf.cell(0, 10, "Scan Quality Assessment", ln=True, align="L")
    
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(120, 120, 120)
    pdf.cell(0, 6, f"Generated: {datetime.now().strftime('%B %d, %Y at %H:%M')}", ln=True)
    pdf.ln(3)
    
    # ── Before / After Images ─────────────────────────────────────────────────
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(20, 20, 60)
    pdf.cell(0, 8, "Before / After Comparison", ln=True)
    pdf.ln(2)
    
    img_w = 85
    pdf.image(orig_thumb,  x=15,      y=pdf.get_y(), w=img_w)
    pdf.image(corr_thumb,  x=110,     y=pdf.get_y(), w=img_w)
    pdf.ln(70)
    
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(100, 100, 100)
    pdf.cell(50, 5, "Original (Warped)", align="C")
    pdf.cell(50, 5, "")
    pdf.cell(50, 5, "Corrected (Dewarped)", align="C")
    pdf.ln(8)
    
    # ── Quality Metrics Table ─────────────────────────────────────────────────
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(20, 20, 60)
    pdf.cell(0, 8, "Quality Metrics", ln=True)
    pdf.ln(2)
    
    metrics = [
        ("Sharpness",      f"{report.sharpness_score:.1f}%",
         _metric_color(report.sharpness_score, 70, 40)),
        ("Blur Level",     report.blur_level,
         _label_color(report.blur_level, good="Low", warn="Medium")),
        ("Brightness",     report.brightness_ok,
         _label_color(report.brightness_ok, good="Good", warn=None)),
        ("Contrast",       report.contrast_ok,
         _label_color(report.contrast_ok, good="Excellent", warn="Good")),
        ("Noise Level",    report.noise_level,
         _label_color(report.noise_level, good="Low", warn="Medium")),
        ("Perspective",    "Correct" if report.perspective_ok else "Distorted",
         ((0, 170, 80) if report.perspective_ok else (220, 50, 50))),
        ("OCR Readiness",  f"{report.ocr_readiness:.1f}%",
         _metric_color(report.ocr_readiness, 75, 50)),
    ]
    
    row_h = 9
    for i, (label, value, color) in enumerate(metrics):
        if i % 2 == 0:
            pdf.set_fill_color(245, 245, 252)
        else:
            pdf.set_fill_color(255, 255, 255)
        
        pdf.set_text_color(40, 40, 40)
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(80, row_h, _clean_latin1(f"  {label}"), border=0, fill=True)
        
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(*color)
        pdf.cell(100, row_h, _clean_latin1(value), border=0, fill=True, ln=True)
    
    pdf.ln(4)
    
    # ── Overall Score ─────────────────────────────────────────────────────────
    pdf.set_fill_color(20, 20, 40)
    pdf.rect(15, pdf.get_y(), 180, 22, "F")
    
    pdf.set_y(pdf.get_y() + 4)
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(255, 255, 255)
    
    stars_str = f"({report.star_rating}/5 stars)"
    pdf.cell(0, 12,
             _clean_latin1(f"  Overall Score: {report.overall_score:.0f} / 100    {stars_str}"),
             align="L", ln=True)
    pdf.ln(8)
    
    # ── Recommendations ───────────────────────────────────────────────────────
    pdf.set_text_color(20, 20, 60)
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 8, "Recommendations", ln=True)
    
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(50, 50, 50)
    for rec in report.recommendations:
        pdf.cell(8, 7, "")
        pdf.set_text_color(0, 140, 80)
        pdf.cell(5, 7, "-")
        pdf.set_text_color(50, 50, 50)
        pdf.cell(0, 7, _clean_latin1(rec), ln=True)
    
    pdf.output(str(output_path))
    _safe_print(f"[EXPORT] PDF report saved -> {output_path}")
    return output_path


