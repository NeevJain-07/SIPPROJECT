# Helpers
# ══════════════════════════════════════════════════════════════════════════════

def _metric_color(score: float, good_thresh: float, warn_thresh: float) -> tuple:
    if score >= good_thresh:
        return (0, 160, 70)    # Green
    elif score >= warn_thresh:
        return (200, 140, 0)   # Amber
    else:
        return (200, 40, 40)   # Red


def _label_color(label: str, good: str, warn: str | None) -> tuple:
    if label == good:
        return (0, 160, 70)
    elif warn and label == warn:
        return (200, 140, 0)
    else:
        return (200, 40, 40)


def _clean_latin1(text: str) -> str:
    if not isinstance(text, str):
        text = str(text)
    replacements = {
        '—': '-',
        '–': '-',
        '’': "'",
        '‘': "'",
        '”': '"',
        '“': '"',
        '★': '*',
        '•': '-',
    }
    for k, v in replacements.items():
        text = text.replace(k, v)
    return text.encode('latin-1', 'replace').decode('latin-1')
